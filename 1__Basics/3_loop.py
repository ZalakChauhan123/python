# Break & Continue With For Loop
# For Loop with Continue
for i in range(1,11):
  if(i==5):
    print("Skip this ITERATION")
    continue
  print(f"{5} * {i} = {5*i}")

print("Loop Ends...")


# Foor Loop with break
for i in range(1,11):
  if(i==5):
    print("Skip this LOOP")
    break
  print(f"{5} * {i} = {5*i}")

print("Loop Ends...")




